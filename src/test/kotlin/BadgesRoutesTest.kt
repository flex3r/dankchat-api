import db.User
import org.jetbrains.exposed.v1.jdbc.Database
import org.jetbrains.exposed.v1.jdbc.transactions.transaction
import kotlin.test.BeforeTest
import kotlin.test.Test
import kotlin.test.assertEquals

class BadgesRoutesTest {

    @BeforeTest
    fun setup() {
        Database.connect("jdbc:h2:mem:badges;DB_CLOSE_DELAY=-1", "org.h2.Driver")
        transaction {
            exec("DROP TABLE IF EXISTS USERS")
            // Schema as created by earlier Exposed versions, the production database still uses it
            exec(
                """
                CREATE TABLE USERS(
                    ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
                    "seId" CHARACTER VARYING(50) NOT NULL UNIQUE,
                    "twitchId" CHARACTER VARYING(50) NOT NULL UNIQUE,
                    NAME CHARACTER VARYING(255) NOT NULL
                )
                """.trimIndent()
            )
            exec("""INSERT INTO USERS("seId", "twitchId", NAME) VALUES ('se1', '1', 'existing')""")
        }
    }

    @Test
    fun `users can be read and written with the legacy schema`() {
        transaction {
            User.new {
                seChannelId = "se2"
                twitchId = "2"
                name = "new"
            }
        }

        val users = transaction { User.all().map { it.twitchId to it.name } }
        assertEquals(listOf("1" to "existing", "2" to "new"), users)
    }
}
